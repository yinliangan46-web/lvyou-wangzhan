    // ========== 机票卡片（可点击购票） ==========
    function makeFlightCard(flights) {
        if (!flights || flights.length === 0) return '';
        const items = flights.map(f => {
            const bookBtn = f.bookingUrl ? `<span class="buy-btn">购票 →</span>` : '';
            return `<a href="${safe(f.bookingUrl)}" target="_blank" class="flight-item">
                <span class="from">${safe(f.from)}</span><span class="arrow">→</span><span class="to">${safe(f.to)}</span>
                <span class="price">${safe(f.price)}</span>
                <span class="time">${safe(f.time)}</span>
                ${bookBtn}
            </a>`;
        }).join('');
        return `<div class="flight-card"><h5><i class="fas fa-plane"></i> ✈️ 机票参考价格</h5>${items}</div>`;
    }

    // ========== 火车卡片（可点击购票） ==========
