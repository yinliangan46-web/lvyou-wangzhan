window.renderMetroBlock = function (cityName, opt) {
    opt = opt || {};
    var m = window.metroForCity(cityName);
    var key = m.key;
    var summary = '';
    var inner = '';

    if (m.data) {
        var d = m.data;
        summary = d.summary;
        inner = d.plans.map(function (p) {
            var badges = p.lines.map(function (l, i) {
                return (i ? '<span class="metro-sep">→</span>' : '') + '<span class="metro-badge">' + l + '</span>';
            }).join('');
            return '<div class="metro-plan">' +
                '<div class="metro-pair"><b>' + p.from + '</b><i class="fas fa-arrow-right"></i><b>' + p.to + '</b></div>' +
                '<div class="metro-line">' + badges + '</div>' +
                '<p class="metro-route">' + p.detail + '</p>' +
                '<div class="metro-meta"><span><i class="far fa-clock"></i> 约 ' + p.mins + ' 分钟</span>' +
                '<span><i class="fas fa-yen-sign"></i> ' + p.fare + '</span></div></div>';
        }).join('') +
            '<p class="metro-note">时间为含步行估算，票价以里程计；线路、站点与首末班以当地地铁 App 为准，早晚高峰请多留 10 分钟。</p>';
    } else if (m.partial) {
        summary = m.partial;
        inner = '<p>' + key + '已开通轨道交通，站内暂未整理逐站换乘方案。出发前在高德地图输入「景点 A → 景点 B」，' +
            '选择「地铁优先」即可看到实时线路、换乘站与首末班。</p>' +
            '<div class="metro-alt"><span>支付宝/微信乘车码</span><span>单程 ¥2–8</span><span>避开 7:30–9:30</span></div>';
    } else {
        summary = '暂无地铁运营';
        inner = '<p>截至 2026 年，' + key + '暂无地铁。市内移动以公交、网约车和景区直通车为主；' +
            '景点之间打车通常在 ¥10–30，公交 1–2 元，扫码即可乘车。</p>' +
            '<div class="metro-alt"><span>公交 ¥1–2</span><span>网约车 ¥10–30</span><span>景区直通车</span></div>';
    }

    if (opt.bare) return '<div class="metro-sum">' + summary + '</div>' + inner;

    return '<div class="metro-card' + (m.data ? '' : ' metro-none') + '"><div class="metro-head">' +
        '<h4><i class="fas fa-subway"></i> 地铁怎么坐</h4><span class="metro-sum">' + summary + '</span></div>' +
        inner + '</div>';
};
